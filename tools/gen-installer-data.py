#!/usr/bin/env python3
"""
Regenerate the installer files that are derived from the DevOS catalogs:

  branding/devos/aimodel-hw.js             default hardware facts (4 GB laptop)
  modules/contextualprocess_aimodel.conf   one job per "Choose your DevOS AI" value
  branding/devos/features-catalog.js       the "Choose your apps" page list

Run after editing components/ai-core/model_catalog.py or
components/features/feature_catalog.py:  python3 tools/gen-installer-data.py
tests/unit/test_ai_models.py and test_features.py fail when these are stale.
"""

import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "components", "ai-core"))
sys.path.insert(0, os.path.join(ROOT, "components", "features"))

import feature_catalog  # noqa: E402
import model_catalog  # noqa: E402
import models_cli  # noqa: E402

CALAMARES = os.path.join(ROOT, "build", "includes.chroot", "etc", "calamares")


def write(rel, text):
    with open(os.path.join(CALAMARES, rel), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def aimodel_files():
    info = models_cli.hardware_info(4.0, 2, "", "", 0.0, True)
    write("branding/devos/aimodel-hw.js",
          ".pragma library\n// Default for a 4 GB laptop; devos-ai-hwprobe rewrites it at live boot.\n"
          "var hw = " + json.dumps(info, indent=1) + ";\n")
    lines = ["# Generated by tools/gen-installer-data.py from components/ai-core/model_catalog.py.",
             "# Writes the model picked on the \"Choose your DevOS AI\" page into the new",
             "# system; devos-ai-models.service downloads it once the PC is online.",
             "# Calamares names the global-storage key packagechooser_<id>; older builds",
             "# use the bare id, so both are listed.",
             "---", "dontChroot: false", "timeout: 60"]
    for key in ("packagechooser_aimodel", "aimodel"):
        lines.append(f"{key}:")
        for value in model_catalog.all_choice_values():
            lines.append(f'    "{value}": "/usr/local/bin/devos-ai-models choose --value {value} --no-download"')
    write("modules/contextualprocess_aimodel.conf", "\n".join(lines) + "\n")


def features_file():
    keep = ("id", "category", "name", "about", "size_mb", "windows", "preinstalled", "presets", "eula",
            "min_ram_gb")
    data = {
        "categories": [{"id": c, "name": n} for c, n in feature_catalog.CATEGORIES],
        "presets": [{"id": p, "name": n, "about": a} for p, n, a in feature_catalog.PRESETS],
        "userTypes": [{"id": i, "name": n, "about": a, "mark": m} for i, n, a, m in feature_catalog.USER_TYPES],
        "features": [dict({k: f[k] for k in keep}, optin=bool((f["builtin"] or {}).get("optin")))
                     for f in feature_catalog.FEATURES],
        "defaults": feature_catalog.default_ids(),
    }
    write("branding/devos/features-catalog.js",
          ".pragma library\n// Generated by tools/gen-installer-data.py from components/features/feature_catalog.py.\n"
          "var data = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n" + RECOMMENDED_JS)


# Same rules as feature_catalog.recommended_ids (test_features checks both agree).
RECOMMENDED_JS = """
function recommended(ramGb, diskGb) {
    var ids = [];
    for (var i = 0; i < data.features.length; i++) {
        var f = data.features[i];
        if (f.presets.indexOf("windows") < 0) continue;
        if (ramGb + 0.5 < f.min_ram_gb) continue;
        if (diskGb > 0 && diskGb < %d && !f.preinstalled && f.size_mb > %d) continue;
        ids.push(f.id);
    }
    if (ids.indexOf("onlyoffice") < 0) ids.unshift("libreoffice");
    return ids;
}

function idsWith(preset) {
    var ids = [];
    for (var i = 0; i < data.features.length; i++)
        if (data.features[i].presets.indexOf(preset) >= 0) ids.push(data.features[i].id);
    return ids;
}

function unionIds() {
    var seen = {};
    for (var a = 0; a < arguments.length; a++) {
        var list = arguments[a];
        for (var i = 0; i < list.length; i++) seen[list[i]] = true;
    }
    var ordered = [];
    for (var j = 0; j < data.features.length; j++)
        if (seen[data.features[j].id]) ordered.push(data.features[j].id);
    return ordered;
}

function userTypeIds(kind, ramGb, diskGb) {
    if (kind === "recommended") kind = "normal";
    var everyday = idsWith("windows");
    if (kind === "normal") return recommended(ramGb, diskGb);
    if (kind === "premium") {
        var all = [];
        for (var i = 0; i < data.features.length; i++)
            if (!data.features[i].optin) all.push(data.features[i].id);
        return all;
    }
    if (kind === "family") return unionIds(recommended(ramGb, diskGb), idsWith("family"));
    if (kind === "islamic") return idsWith("islamic");
    if (kind === "professional") return unionIds(everyday, idsWith("professional"));
    if (kind === "business") return unionIds(everyday, idsWith("professional"), idsWith("business"));
    if (kind === "student" || kind === "developer" || kind === "creator" || kind === "gamer")
        return unionIds(everyday, idsWith(kind));
    return recommended(ramGb, diskGb);
}
""" % (feature_catalog.SMALL_DISK_GB, feature_catalog.BIG_DOWNLOAD_MB)


if __name__ == "__main__":
    aimodel_files()
    features_file()
    print("Installer data regenerated.")
